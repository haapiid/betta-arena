// Copies the compiled ABIs into src/chain/abi.ts so the server and the web app share typed ABIs.
// Run after `npx hardhat build`: node scripts/export-abi.mjs
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const out = path.join(root, '..', 'src', 'chain', 'abi.ts')
const names = ['BettaFish', 'BettaShop', 'BettaArena', 'MockBetta']
const src = { MockBetta: 'mocks/MockBetta.sol' }

let ts = '// Generated by contracts/scripts/export-abi.mjs. Do not edit by hand.\n\n'
for (const n of names) {
  const file = path.join(root, 'artifacts', 'contracts', src[n] ?? `${n}.sol`, `${n}.json`)
  const { abi } = JSON.parse(fs.readFileSync(file, 'utf8'))
  const id = n[0].toLowerCase() + n.slice(1)
  ts += `export const ${id}Abi = ${JSON.stringify(abi, null, 2)} as const\n\n`
}
// any ERC-20 works for the token itself; the mock's ABI covers the calls the game makes
ts += 'export const erc20Abi = mockBettaAbi\n'
fs.writeFileSync(out, ts)
console.log(`wrote ${path.relative(process.cwd(), out)}`)
